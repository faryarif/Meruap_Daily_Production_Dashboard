create table if not exists public.whatsapp_daily_reports (
    id bigint generated by default as identity primary key,
    report_date date not null,
    source_message text not null check (length(btrim(source_message)) > 0),
    payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
    created_at timestamptz not null default now()
);

create index if not exists whatsapp_daily_reports_report_date_created_idx
    on public.whatsapp_daily_reports (report_date desc, created_at desc);

alter table public.whatsapp_daily_reports enable row level security;

revoke all on table public.whatsapp_daily_reports from public, anon, authenticated;
grant select, insert on table public.whatsapp_daily_reports to service_role;

drop policy if exists "Service role manages WhatsApp daily reports"
    on public.whatsapp_daily_reports;
create policy "Service role manages WhatsApp daily reports"
    on public.whatsapp_daily_reports
    for all
    to service_role
    using (true)
    with check (true);
